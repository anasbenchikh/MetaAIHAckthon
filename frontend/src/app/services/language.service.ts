@Injectable({ providedIn: 'root' })
export class LanguageService {
  private readonly storageKey = 'plombier-lang';

  readonly current = signal<Lang>(this.readStored());

  set(lang: Lang): void {
    this.current.set(lang);
    try {
      localStorage.setItem(this.storageKey, lang);
    } catch {
      /* storage unavailable */
    }
  }

  t(key: string): string {
    return STRINGS[this.current()][key] ?? STRINGS.fr[key] ?? key;
  }

  private readStored(): Lang {
    try {
      return localStorage.getItem(this.storageKey) === 'en' ? 'en' : 'fr';
    } catch {
      return 'fr';
    }
  }
}
